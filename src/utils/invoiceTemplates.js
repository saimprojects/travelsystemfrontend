// Helper: build inclusions + duration sub-rows below service name in table
export const buildServiceMeta = (invoiceData, color = "#64748b") => {
  let html = "";
  if (invoiceData.serviceDuration) {
    html += `<div style="font-size:11px;color:${color};margin-top:4px">${IC.clock}<strong>Duration:</strong> ${invoiceData.serviceDuration}</div>`;
  }
  if (Array.isArray(invoiceData.serviceInclusions) && invoiceData.serviceInclusions.length) {
    html += `<div style="font-size:11px;color:${color};margin-top:3px;line-height:1.8">${invoiceData.serviceInclusions.map(i => `<span style="margin-right:10px">${IC.check}${i}</span>`).join("")}</div>`;
  }
  return html;
};

